/** Interpolate {placeholder} values in a translated string. */
function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** React hook: returns a t() function bound to the current language. */
export function useT() {
  const lang = useGameStore((s) => s.profile.displayLang ?? "en");

  return function t(key: string, vars?: Record<string, string | number>): string {
    const langStrings = strings[lang] ?? strings.en;
    const str = langStrings[key] ?? strings.en[key] ?? key;
    return interpolate(str, vars);
  };
}

/** Server/non-hook version: pass lang explicitly. */
export function translate(lang: DisplayLang, key: string, vars?: Record<string, string | number>): string {
  const langStrings = strings[lang] ?? strings.en;
  const str = langStrings[key] ?? strings.en[key] ?? key;
  return interpolate(str, vars);
}

